const look=(from,to)=>{
  const dx=to.x-from.x,dz=to.z-from.z,dy=(to.y??1.65)-(from.y??1.65),distance=Math.hypot(dx,dz);
  return {...from,y:from.y??1.65,yaw:Math.atan2(-dx,-dz),pitch:Math.atan2(dy,distance)};
};
const flowerDream=()=>generateDream('flower-audit-000',{catEnabled:false,preferences:['like.flower']});

test('B01 flowers bind to a real door while its center remains traversable',()=>{
  const dream=flowerDream(),instance=dream.flatMap(plan=>plan.content.instances).find(item=>item.definitionId==='B01');
  assert.ok(instance);
  const plan=dream.find(layer=>layer.content.instances.includes(instance));
  assert.equal(validatePlan(plan).valid,true);
  const door=plan.doors.find(item=>item.id===instance.entryDoorId);assert.ok(door);
  assert.ok(Math.hypot(instance.doorFrame.x-door.x,instance.doorFrame.z-door.z)<.001);
  assert.ok(!plan.obstacles.some(box=>door.x>=box.minX&&door.x<=box.maxX&&door.z>=box.minZ&&door.z<=box.maxZ));
  const state=createStoryState(),boxes=[...plan.walls,...plan.obstacles];
  stepContent(plan,state,look(instance.observation,instance.focus),.75,boxes);
  assert.equal(state.instances[instance.instanceId].phase,'observed');
  assert.equal(state.cue?.text,'喜欢就多放一点。门嘛，侧着身总能过去。');
  assert.equal(plan.threat,null);
});

test('B03 stays fresh until observed normal departure, then visibly withers on return',()=>{
  const dream=flowerDream(),first=dream[0],instance=first.content.instances.find(item=>item.definitionId==='B03');
  assert.ok(instance);assert.equal(validatePlan(first).valid,true);
  assert.ok(dream.flatMap(plan=>plan.content.instances).filter(item=>item.definitionId==='B03').length===1);
  const boxes=[...first.walls,...first.obstacles],view=look(instance.observation,instance.focus);
  const door=first.doors.find(item=>item.id===instance.entryDoorId),axis=door.axis,other=axis==='x'?'z':'x';
  const inside=door.cells.find(([x,z])=>first.cells.find(cell=>cell.x===x&&cell.z===z)?.roomId===instance.roomId);
  const sign=Math.sign(inside[axis==='x'?0:1]*first.cellSize-door[axis]);
  const near={...view,[axis]:door[axis]+sign*.25,[other]:door[other]};
  const far={...near,[axis]:door[axis]-sign*.25};
  const unseen=createStoryState();
  stepStory(first,unseen,near,.01,{suppressRoutes:true,boxes});
  stepStory(first,unseen,far,.01,{suppressRoutes:true,boxes});
  assert.equal(unseen.instances[instance.instanceId].phase,'waiting');
  const state=createStoryState();stepContent(first,state,view,.85,boxes);
  assert.equal(state.instances[instance.instanceId].phase,'observed');
  assert.equal(state.cue?.text,'照你喜欢的摆的。');
  state.cue=null;
  stepStory(first,state,near,.01,{suppressRoutes:true,boxes});
  stepStory(first,state,far,.01,{suppressRoutes:true,boxes});
  assert.equal(state.instances[instance.instanceId].phase,'withered');
  const scene=new THREE.Scene(),world=createWorld(scene,first),flowers=scene.getObjectByName(`story-${instance.instanceId}-flowers`);
  assert.ok(flowers);world.updateStory(state,view);
  assert.equal(scene.getObjectByName(`story-${instance.instanceId}-bloom`).visible,false);
  assert.equal(scene.getObjectByName(`story-${instance.instanceId}-withered`).visible,true);
  stepStory(first,state,near,.01,{suppressRoutes:true,boxes});
  stepContent(first,state,view,.85,boxes);
  assert.equal(state.instances[instance.instanceId].phase,'witheredSeen');
  assert.equal(state.cue?.text,'哎呀，颜色深了一点。');
  assert.ok(state.facts.includes(`${instance.instanceId}.witheredSeen`));
  world.dispose();
  const invalid=structuredClone(first);invalid.content.preferences=[];
  assert.ok(validatePlan(invalid).errors.includes('UNCONFIRMED_CONTENT_PREFERENCE:B03'));
});

test('B27 restores the same flower vase only after the first-layer wilt was actually seen',()=>{
  const [first,second]=flowerDream();
  const source=first.content.instances.find(item=>item.definitionId==='B03');
  const slot=second.content.conditionalSlots.find(item=>item.id==='B27');
  assert.ok(source);assert.ok(slot);assert.equal(slot.sourceInstanceId,source.instanceId);
  assert.equal(validatePlan(second).valid,true);
  const boxes=[...first.walls,...first.obstacles],view=look(source.observation,source.focus);
  const door=first.doors.find(item=>item.id===source.entryDoorId),axis=door.axis,other=axis==='x'?'z':'x';
  const inside=door.cells.find(([x,z])=>first.cells.find(cell=>cell.x===x&&cell.z===z)?.roomId===source.roomId);
  const sign=Math.sign(inside[axis==='x'?0:1]*first.cellSize-door[axis]);
  const near={...view,[axis]:door[axis]+sign*.25,[other]:door[other]};
  const far={...near,[axis]:door[axis]-sign*.25};
  const state=createState(first,'generic','flower',1);
  stepContent(first,state.story,view,.85,boxes);state.story.cue=null;
  stepStory(first,state.story,near,.01,{suppressRoutes:true,boxes});
  stepStory(first,state.story,far,.01,{suppressRoutes:true,boxes});
  assert.equal(state.story.instances[source.instanceId].phase,'withered');
  state.player.standing=true;
  assert.equal(requestDeath(state),true);
  assert.equal(commitTransition(state,stepTransition(state,.6).id,first),true);
  assert.equal(state.story.instances[source.instanceId].phase,'withered');
  state.flow.transition=null;state.flow.phase='exploring';state.flow.graceRemaining=0;
  stepStory(first,state.story,near,.01,{suppressRoutes:true,boxes});
  stepContent(first,state.story,view,.85,boxes);
  assert.ok(state.story.facts.includes(`${source.instanceId}.witheredSeen`));
  const dollSource=first.content.instances.find(item=>item.definitionId==='B04');
  if(dollSource)state.story.facts.push(`${dollSource.instanceId}.tearSeen`);
  state.story.cue=null;
  state.player.standing=true;
  const exitView={...first.exit,y:1.65,yaw:0,pitch:0};
  assert.equal(requestExit(state,first,exitView,boxes),true);
  assert.equal(commitTransition(state,stepTransition(state,.6).id,second),true);
  assert.equal(state.story.conditional.B27?.sourceInstanceId,source.instanceId);
  assert.equal(state.story.conditional.B28,undefined);
  const scene=new THREE.Scene(),world=createWorld(scene,second),flowers=scene.getObjectByName('story-B27');
  assert.ok(flowers);assert.equal(flowers.visible,false);
  world.updateStory(state.story,state.player);assert.equal(flowers.visible,true);
  const secondBoxes=[...second.walls,...second.obstacles];
  const bedside=look({x:0,y:1.65,z:0},slot.focus);
  stepContent(second,state.story,bedside,.9,secondBoxes);
  assert.equal(state.story.conditional.B27.phase,'waiting');
  state.story.consumed.push('flow.falseWake');
  stepContent(second,state.story,bedside,.9,secondBoxes);
  assert.equal(state.story.conditional.B27.phase,'seen');
  assert.equal(state.story.cue?.text,'这不还好好的吗？你看得太认真了。');
  world.dispose();

  const unseen=createState(first,'generic','flower',1);unseen.player.standing=true;
  assert.equal(requestExit(unseen,first,exitView,boxes),true);
  assert.equal(commitTransition(unseen,stepTransition(unseen,.6).id,second),true);
  assert.equal(unseen.story.conditional.B27,undefined);
});
